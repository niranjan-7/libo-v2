import React, { useState } from 'react';
import { useAuth } from '../context/AuthContext';
import { useToast } from './ui/Toast';
import { KeyRound, X, AlertCircle, CheckCircle2 } from 'lucide-react';

interface Props {
  isOpen: boolean;
  onClose: () => void;
  initialToken?: string;
}

export const AcceptInviteModal: React.FC<Props> = ({ isOpen, onClose, initialToken = '' }) => {
  const { acceptInvite } = useAuth();
  const { showToast } = useToast();
  const [token, setToken] = useState(initialToken);
  const [error, setError] = useState<string | null>(null);
  const [isSubmitting, setIsSubmitting] = useState(false);

  // Sync initialToken if provided
  React.useEffect(() => {
    if (initialToken) {
      setToken(initialToken);
    }
  }, [initialToken]);

  if (!isOpen) return null;

  const handleSubmit = async (e: React.FormEvent) => {
    e.preventDefault();
    setError(null);
    const trimmed = token.trim();
    if (!trimmed) {
      setError('Please enter your invitation token.');
      return;
    }

    setIsSubmitting(true);
    try {
      await acceptInvite(trimmed);
      showToast('Successfully joined organization!', 'success');
      onClose();
    } catch (err: any) {
      setError(err.message || 'Failed to accept invitation. Token may be invalid or expired.');
    } finally {
      setIsSubmitting(false);
    }
  };

  return (
    <div style={{
      position: 'fixed',
      inset: 0,
      background: 'rgba(0,0,0,0.45)',
      backdropFilter: 'blur(4px)',
      display: 'grid',
      placeItems: 'center',
      zIndex: 100,
      padding: '20px',
    }}>
      <div style={{
        background: 'var(--surface)',
        borderRadius: 'var(--radius)',
        border: '1px solid var(--border)',
        boxShadow: 'var(--shadow)',
        width: '100%',
        maxWidth: '460px',
        padding: '28px',
        position: 'relative',
      }}>
        <button
          onClick={onClose}
          style={{
            position: 'absolute',
            top: '20px',
            right: '20px',
            background: 'transparent',
            border: 'none',
            color: 'var(--muted)',
            cursor: 'pointer',
          }}
          aria-label="Close"
        >
          <X size={20} />
        </button>

        <div style={{ display: 'flex', alignItems: 'center', gap: '12px', marginBottom: '16px' }}>
          <div style={{
            width: '40px',
            height: '40px',
            borderRadius: '12px',
            background: 'var(--accent-soft)',
            color: 'var(--accent)',
            display: 'grid',
            placeItems: 'center',
          }}>
            <KeyRound size={22} />
          </div>
          <div>
            <h2 style={{ margin: 0, fontSize: '18px', fontWeight: 800 }}>Join Existing Organization</h2>
            <p style={{ margin: '2px 0 0', fontSize: '12px', color: 'var(--muted)' }}>
              Enter your invitation token to access the organization
            </p>
          </div>
        </div>

        {error && (
          <div style={{
            display: 'flex',
            gap: '8px',
            background: 'var(--danger)',
            color: 'var(--danger-text)',
            padding: '10px 14px',
            borderRadius: '10px',
            marginBottom: '16px',
            fontSize: '12px',
          }}>
            <AlertCircle size={16} style={{ flexShrink: 0 }} />
            <div>{error}</div>
          </div>
        )}

        <form onSubmit={handleSubmit}>
          <div style={{ marginBottom: '18px' }}>
            <label style={{ display: 'block', fontSize: '12px', fontWeight: 700, marginBottom: '6px' }}>
              Invitation Token
            </label>
            <input
              type="text"
              required
              value={token}
              onChange={(e) => setToken(e.target.value)}
              placeholder="Paste your 64-character invite token here"
              disabled={isSubmitting}
              style={{
                width: '100%',
                padding: '11px 14px',
                borderRadius: '10px',
                border: '1px solid var(--border)',
                background: 'var(--canvas)',
                color: 'var(--text)',
                fontFamily: 'monospace',
                fontSize: '12px',
              }}
            />
            <small style={{ color: 'var(--muted)', fontSize: '11px', display: 'block', marginTop: '6px', lineHeight: 1.4 }}>
              This token was generated by your institution's librarian or organization owner.
            </small>
          </div>

          <div style={{ display: 'flex', justifyContent: 'flex-end', gap: '10px' }}>
            <button
              type="button"
              onClick={onClose}
              disabled={isSubmitting}
              className="btn"
            >
              Cancel
            </button>
            <button
              type="submit"
              disabled={isSubmitting || !token.trim()}
              className="btn primary"
            >
              {isSubmitting ? 'Verifying...' : 'Join Organization'}
            </button>
          </div>
        </form>
      </div>
    </div>
  );
};
